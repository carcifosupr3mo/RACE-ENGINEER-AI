@dataclass
class Check:
    id: str
    ok: bool | None          # None = cannot be determined
    title: str
    detail: str = ""
    fix: str = ""


@dataclass
class DiagnosticReport:
    checks: list[Check] = field(default_factory=list)
    verdict: str = ""

    def to_json(self) -> dict:
        return asdict(self)


def header_field_drift(header_dir: str | Path) -> dict:
    """Name-only drift check of our layout against the installed S397 headers.

    Verifies that every field name we map exists as a word in the installed headers. It does NOT
    verify types, order, sizes or offsets - a clean result is necessary, not sufficient.
    """
    texts = []
    for p in Path(header_dir).glob("*.h*"):
        try:
            texts.append(p.read_text(encoding="utf-8", errors="replace"))
        except OSError:
            pass
    blob = "\n".join(texts)
    if not blob:
        return {"checked": False, "reason": "no header text readable"}
    names = set()
    for cls in (L.Wheel, L.VehicleTelemetry, L.VehicleScoring, L.ScoringInfo, L.AppState, L.Generic, L.TelemetryData, L.ScoringData):
        names |= {n for n, _ in cls._fields_}
    missing = sorted(n for n in names if not re.search(r"\b%s\b" % re.escape(n), blob))
    return {"checked": True, "fields_total": len(names), "missing_in_header": missing}


def build_report(install: LmuInstall, process_running: bool | None, mapping_size: int | None,
                 mapping_error: str | None, game_version: int | None, platform: str,
                 synthetic: bool = False) -> DiagnosticReport:
    r = DiagnosticReport()
    add = r.checks.append
    add(Check("platform", platform in ("win32", "linux"), f"Platform: {platform}",
              "LMU runs on Windows; on other platforms only synthetic data or a Wine bridge can be used."
              if platform != "win32" else ""))
    add(Check("install", install.found, "LMU installation found" if install.found else "LMU installation not found",
              install.game_dir or "searched: " + "; ".join(install.searched[:6]),
              "" if install.found else "Install LMU via Steam or set the LMU_GAME_DIR environment variable."))
    add(Check("userdata", bool(install.user_data), "UserData folder", install.user_data or ""))
    add(Check("telemetry_dir", bool(install.telemetry_dir), "UserData/Telemetry folder (native DuckDB recording)",
              f"{len(install.duckdb_files)} .duckdb file(s)" if install.telemetry_dir else "; ".join(install.notes)))
    add(Check("process", process_running, "LMU process running",
              "" if process_running is not None else "cannot be determined on this platform",
              "" if process_running else "Start Le Mans Ultimate."))
    if synthetic:
        add(Check("mapping", None, "Mapping is SYNTHETIC: LMU is NOT being read",
                  "The connected buffer is generated by the test harness; it says nothing about the real game.",
                  "Run without --synthetic while LMU is open to verify the real acquisition."))
    elif mapping_error is None and mapping_size is not None:
        add(Check("mapping", True, f"Shared memory mapping '{L.LMU_SHARED_MEMORY_NAME}' present",
                  f"real size {mapping_size} B, expected >= {L.MAPPING_SIZE} B"))
        add(Check("mapping_size", mapping_size >= L.MAPPING_SIZE, "Mapping size matches the layout used by this software",
                  f"{mapping_size} vs {L.MAPPING_SIZE}",
                  "" if mapping_size >= L.MAPPING_SIZE else
                  "The installed LMU uses a different layout version: update the layout from <LMU>/Support/SharedMemoryInterface."))
        add(Check("game_version", None, "Game version reported in mapping (generic.gameVersion)", str(game_version)))
    else:
        add(Check("mapping", False, f"Shared memory mapping '{L.LMU_SHARED_MEMORY_NAME}' NOT available", mapping_error or "",
                  "In LMU open Settings > Gameplay, enable 'Enable Plugins', then FULLY restart LMU. "
                  "This software never changes game settings by itself."))
    if install.shared_memory_header_dir:
        d = header_field_drift(install.shared_memory_header_dir)
        if d.get("checked"):
            add(Check("header_drift", not d["missing_in_header"], "Layout field names vs installed SharedMemoryInterface headers",
                      f"{d['fields_total']} names checked (names only, not offsets); missing: {d['missing_in_header'][:12]}",
                      "" if not d["missing_in_header"] else "Layout drift suspected: review layout.py against the installed headers."))
    else:
        add(Check("header_drift", None, "Installed SharedMemoryInterface headers not found",
                  "Layout correctness cannot be cross-checked against the installed game."))
    if install.plugin_setting_hints:
        add(Check("plugins_setting", None, "Settings keys mentioning 'plugin' (UNVERIFIED location)",
                  "; ".join(f"{h['key']}={h['value']}" for h in install.plugin_setting_hints[:4])))
    ok_map = mapping_error is None and mapping_size is not None and not synthetic
    r.verdict = ("SYNTHETIC session: real LMU access NOT verified." if synthetic else "Shared memory reachable." if ok_map else
                 "Shared memory not reachable: follow the failed checks above (fallback order: LMU present -> "
                 "Enable Plugins -> game version -> mapping list -> logs). No external plugin will be installed automatically.")
    return r
